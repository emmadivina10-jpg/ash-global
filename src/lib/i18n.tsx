const DICT: Record<Lang, Partial<Record<TKey, string>>> = {
  en: EN,
  fr: FR,
};

type Vars = Record<string, string | number>;

/** Narrows any selected language to the two ASH carries full copy in. */
export function baseLang(lang: Lang): "en" | "fr" {
  return lang === "fr" ? "fr" : "en";
}

function translate(lang: Lang, key: TKey, vars?: Vars) {
  const raw = DICT[lang]?.[key] ?? GENERATED_DICTS[lang]?.[key] ?? EN[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/{(\w+)}/g, (_m, name: string) => String(vars[name] ?? `{${name}}`));
}

function translateText(lang: Lang, en: string, fr?: string) {
  if (lang === "en") return en;
  if (lang === "fr" && fr) return fr;
  return GENERATED_DICTS[lang]?.[`literal:${en}`] ?? en;
}

const I18nContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey, v?: Vars) => string;
  tx: (en: string, fr?: string) => string;
}>({
  lang: "en",
  setLang: () => {},
  t: (k, v) => translate("en", k, v),
  tx: (en) => en,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    setLangState(readLanguage(localStorage, navigator.language));
    const sync = (event: StorageEvent) => {
      if (event.key === LANGUAGE_STORAGE_KEY)
        setLangState(readLanguage(localStorage, navigator.language));
    };
    window.addEventListener("storage", sync);
    return () => window.removeEventListener("storage", sync);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL_LANGS.has(lang) ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    saveLanguage(localStorage, l);
  }, []);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      t: (k: TKey, v?: Vars) => translate(lang, k, v),
      tx: (en: string, fr?: string) => translateText(lang, en, fr),
    }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

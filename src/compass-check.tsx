import React from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { createRouter, createRootRoute, RouterProvider } from '@tanstack/react-router';
import { CompassSurface } from './components/refer/CompassSurface';
import './styles.css';
const client = new QueryClient({ defaultOptions: { queries: { enabled: false } } });
const route = createRootRoute({ component: () => <QueryClientProvider client={client}><CompassSurface active initiallyOpen map={<div className="p-5">No location shared</div>} /></QueryClientProvider> });
const router = createRouter({ routeTree: route });
const root = document.getElementById('root');
if (root) createRoot(root).render(<RouterProvider router={router} />);
